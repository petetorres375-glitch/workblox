SYSTEM_PROMPT = """\
You are a helpful document analyst. Analyze the provided document and return a JSON object with exactly these four keys:
- "summary": A 2-3 sentence overview of the document.
- "key_data_points": A list of important names, dates, amounts, or figures as bullet points.
- "action_items": A list of tasks, deadlines, or next steps. If none, return ["None identified."].
- "red_flags": A list of concerns, risks, or missing information. If none, return ["None identified."].

Return only valid JSON. No markdown fences, no extra text.
"""

_PHOTO_INSTRUCTION = (
    "Analyze the document shown in the attached photo(s). If there are multiple "
    "photos, treat them as consecutive pages of the same document, in the order given."
)


# The client sends the section headings already translated, because the
# backend has no locale files of its own. English is only the fallback.
_DEFAULT_LABELS = {
    "report_title":    "Analysis Report",
    "summary":         "Summary",
    "key_data_points": "Key Data Points",
    "action_items":    "Action Items",
    "red_flags":       "Red Flags",
}


def _labels_from(body: dict) -> dict:
    supplied = body.get("labels") or {}
    return {
        key: (str(supplied.get(key) or "").strip() or default)
        for key, default in _DEFAULT_LABELS.items()
    }


def _build_txt_report(filename: str, result: dict, labels: dict | None = None) -> str:
    labels = labels or _DEFAULT_LABELS
    lines = [
        f"{labels['report_title']}: {filename}",
        "Generated by Workblox — Torres Tech Remote",
        "",
    ]
    sections = [
        (labels["summary"],         result.get("summary", "")),
        (labels["key_data_points"], result.get("key_data_points", [])),
        (labels["action_items"],    result.get("action_items", [])),
        (labels["red_flags"],       result.get("red_flags", [])),
    ]
    for title, content in sections:
        lines.append(title)
        lines.append("-" * len(title))
        if isinstance(content, list):
            for item in content:
                lines.append(f"  - {item}")
        else:
            lines.append(content)
        lines.append("")
    return "\n".join(lines)


@bp.post("/api/doc")
@limiter.limit("10 per hour")
def doc_analyzer():
    guard = require_personal() or require_tool("doc")
    if guard:
        return guard
    file = request.files.get("file")
    images = [f for f in request.files.getlist("images") if f and f.filename]
    language = (request.form.get("language") or "en").strip()

    if file and file.filename and images:
        return jsonify({"error": "Provide either a file or photos, not both"}), 400

    if images:
        if len(images) > claude_client.MAX_IMAGES:
            return jsonify({"error": f"Too many photos — {claude_client.MAX_IMAGES} max per submission"}), 400
        try:
            image_blocks = [claude_client.to_image_content(prepare_image(img)) for img in images]
        except ValueError as e:
            return jsonify({"error": str(e)}), 415

        try:
            result = claude_client.call(
                system_prompt=SYSTEM_PROMPT,
                user_message=_PHOTO_INSTRUCTION,
                model="claude-sonnet-4-6",
                max_tokens=2048,
                language=language,
                images=image_blocks,
            )
        except Exception as e:
            return jsonify({"error": str(e)}), 500
        return jsonify(result)

    if not file or not file.filename:
        return jsonify({"error": "file is required"}), 400

    try:
        text = extract_text(file)
    except ValueError as e:
        return jsonify({"error": str(e)}), 415
    except Exception as e:
        return jsonify({"error": f"Could not read file: {e}"}), 422

    if not text.strip():
        return jsonify({"error": "Could not extract any text from the file"}), 422

    try:
        result = claude_client.call(
            system_prompt=SYSTEM_PROMPT,
            user_message=f"Document: {file.filename}\n\nContent:\n{text}",
            model="claude-sonnet-4-6",
            max_tokens=2048,
            language=language,
        )
    except Exception as e:
        return jsonify({"error": str(e)}), 500

    return jsonify(result)


@bp.post("/api/doc/download/pdf")
@limiter.limit("10 per hour")
def doc_download_pdf():
    guard = require_personal() or require_tool("doc")
    if guard:
        return guard
    from fpdf import FPDF

    from ..services.pdf_fonts import BASE_FONT, align_for, register_pdf_fonts

    body     = request.get_json(silent=True) or {}
    filename = (body.get("filename") or "document").strip()
    language = (body.get("language") or "").strip()
    labels   = _labels_from(body)
    result   = body.get("result")
    if not result:
        return jsonify({"error": "result is required"}), 400

    C_INK   = (15,  23,  42)
    C_BLUE  = (37,  99, 235)
    C_SOFT  = (100,116, 139)
    C_RED   = (220, 38,  38)
    C_RULE  = (226,232, 240)
    W = 180

    class _PDF(FPDF):
        def __init__(self):
            super().__init__()
            register_pdf_fonts(self)

        def sec(self, title, color):
            self.ln(4)
            self.set_font(BASE_FONT, "B", 8)
            self.set_text_color(*color)
            # Left in natural case: .upper() corrupts Turkish (i -> I) and does
            # nothing for the non-cased scripts.
            self.cell(W, 5, title)
            self.ln(5)
            self.set_draw_color(*color)
            self.set_line_width(0.3)
            self.line(15, self.get_y(), 195, self.get_y())
            self.ln(3)
            self.set_text_color(*C_INK)
            self.set_draw_color(0, 0, 0)

    pdf = _PDF()
    pdf.set_auto_page_break(True, 15)
    pdf.add_page()
    pdf.set_margins(15, 15, 15)

    pdf.set_fill_color(*C_INK)
    pdf.rect(0, 0, 210, 26, "F")
    pdf.set_xy(15, 7)
    pdf.set_font(BASE_FONT, "B", 13)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(W, 7, labels["report_title"])
    pdf.ln(8)
    pdf.set_x(15)
    pdf.set_font(BASE_FONT, "", 8.5)
    pdf.set_text_color(180, 190, 210)
    now = datetime.now().strftime("%B %d, %Y  %H:%M")
    pdf.cell(W, 5, f"{filename}   |   {now}   |   Workblox — Torres Tech Remote")
    pdf.ln(16)

    sections = [
        (labels["summary"],         result.get("summary", ""),         C_BLUE, False),
        (labels["key_data_points"], result.get("key_data_points", []), C_BLUE, True),
        (labels["action_items"],    result.get("action_items", []),    C_BLUE, True),
        (labels["red_flags"],       result.get("red_flags", []),       C_RED,  True),
    ]
    # Direction is decided from the whole report so every section agrees.
    align = align_for(" ".join(str(c) for _, c, _, _ in sections
                              if not isinstance(c, list)) or "", language)
    for title, content, color, is_list in sections:
        pdf.sec(title, color)
        pdf.set_font(BASE_FONT, "", 9.5)
        pdf.set_text_color(*C_INK)
        if is_list and isinstance(content, list):
            for item in content:
                pdf.set_x(15)
                if align == "R":
                    # A separate bullet cell is pinned to the left margin, which
                    # strands it on the wrong side of right-aligned text. Inline
                    # it instead and let the shaper put it on the leading edge.
                    pdf.multi_cell(W, 6, f"• {item}", align=align)
                else:
                    pdf.cell(5, 6, "•")
                    pdf.set_x(20)
                    pdf.multi_cell(W - 5, 6, item, align=align)
        else:
            pdf.set_x(15)
            pdf.multi_cell(W, 6, str(content), align=align)
        pdf.ln(1)

    pdf.set_auto_page_break(False)
    pdf.set_y(pdf.h - 14)
    pdf.set_font(BASE_FONT, "", 7.5)
    pdf.set_text_color(*C_SOFT)
    pdf.cell(W, 5, f"Generated by Workblox — Torres Tech Remote  |  {now}", align="C")

    buf = io.BytesIO()
    pdf.output(buf)
    buf.seek(0)
    stem = Path(filename).stem
    return send_file(buf, as_attachment=True,
        download_name=f"{stem}_report.pdf",
        mimetype="application/pdf")


@bp.post("/api/doc/email")
@limiter.limit("10 per hour")
def doc_email():
    guard = require_personal() or require_tool("doc")
    if guard:
        return guard
    body = request.get_json(silent=True) or {}
    email_addr = (body.get("email") or "").strip()
    filename = (body.get("filename") or "document").strip()
    result = body.get("result")

    if not email_addr or not EMAIL_RE.match(email_addr):
        return jsonify({"error": "Valid email address is required"}), 400
    if not result:
        return jsonify({"error": "result is required"}), 400

    api_key = os.getenv("SENDGRID_API_KEY")
    if not api_key:
        return jsonify({"error": "Email is not configured on this server"}), 503

    txt_report = _build_txt_report(filename, result, _labels_from(body))
    stem = Path(filename).stem

    payload = {
        "personalizations": [{"to": [{"email": email_addr}]}],
        "from": {"email": FROM_EMAIL, "name": FROM_NAME},
        "subject": f"Doc Analyzer Report: {filename}",
        "content": [{"type": "text/plain", "value": (
            "Your document analysis report is attached.\n\n"
            "Generated by Workblox — Torres Tech Remote"
        )}],
        "attachments": [{
            "content": base64.b64encode(txt_report.encode("utf-8")).decode(),
            "type": "text/plain",
            "filename": f"{stem}_report.txt",
        }],
    }

    req = urllib.request.Request(
        "https://api.sendgrid.com/v3/mail/send",
        data=json.dumps(payload).encode(),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            resp.read()
    except urllib.error.HTTPError as e:
        body_err = e.read().decode("utf-8", errors="replace")
        return jsonify({"error": f"SendGrid error {e.code}: {body_err}"}), 500

    return jsonify({"success": True})
