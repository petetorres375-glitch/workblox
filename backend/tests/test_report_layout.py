def _doc_pdf(client, token, n_points, tz="America/New_York"):
    result = {
        "summary": "Summary text. " * 15,
        "key_data_points": [f"Data point {i} with some detail" for i in range(1, n_points + 1)],
        "action_items": [f"Action {i}" for i in range(1, 5)],
        "red_flags": [f"Flag {i}" for i in range(1, 5)],
    }
    rv = client.post("/api/doc/download/pdf",
                     json={"filename": "notice.pdf", "result": result, "language": "en"},
                     headers={"Authorization": f"Bearer {token}", "X-Timezone": tz})
    assert rv.status_code == 200
    return rv.data


def test_doc_pdf_prints_the_users_local_time(doc_client):
    client, token = doc_client
    text = _pages(_doc_pdf(client, token, 3, tz="Asia/Tokyo"))[0]
    stamp = re.search(r"(\w+ \d{2}, \d{4})\s+(\d{2}:\d{2})", text)
    printed = datetime.strptime(f"{stamp.group(1)} {stamp.group(2)}", "%B %d, %Y %H:%M")
    tokyo_now = datetime.now(ZoneInfo("Asia/Tokyo")).replace(tzinfo=None, second=0, microsecond=0)
    assert abs((printed - tokyo_now).total_seconds()) <= 120


def test_doc_pdf_never_ends_a_page_on_a_heading(doc_client):
    client, token = doc_client
    doc_headings = {"Summary", "Key Data Points", "Action Items", "Red Flags"}
    for n in range(1, 50, 2):
        for page in _pages(_doc_pdf(client, token, n)):
            assert _last_body_line(page) not in doc_headings, f"stranded heading at n={n}"
